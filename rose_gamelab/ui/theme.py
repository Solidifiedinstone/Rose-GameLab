"""Theming: colour palettes and the stylesheet built from them.

A theme is a flat set of named colours. Everything visual derives from those
names, so a new theme is a dozen colour values and needs no stylesheet work.
Themes are plain data and round-trip through JSON, which is what lets users
share them and lets GameLab pick up colours generated by Matugen or any other
palette tool.

The default is tuned for OLED panels: true black rather than dark grey, because
black pixels are genuinely off and the difference is visible.
"""

from __future__ import annotations

import json

from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Optional

# Corner radius, spacing and sizing live here rather than being sprinkled
# through the stylesheet, so the whole interface can be tightened or loosened
# from one place.
RADIUS_LARGE = 18
RADIUS = 12
RADIUS_SMALL = 8
SPACING = 12

# Cover art is 2:3, the standard portrait box-art ratio Steam and every
# thumbnail archive use.
COVER_RATIO = 3 / 2
COVER_WIDTHS = {"small": 120, "medium": 160, "large": 200, "huge": 260}


@dataclass
class Theme:
    """A named colour palette."""

    name: str = "Rose Dark"
    background: str = "#000000"
    surface: str = "#0d0d10"
    panel: str = "#14141a"
    elevated: str = "#1c1c24"
    accent: str = "#e0607e"
    accent_muted: str = "#8c3d4f"
    text: str = "#e8e6ea"
    text_dim: str = "#8a8791"
    border: str = "#22222c"
    success: str = "#7fc98a"
    warning: str = "#e0b060"
    error: str = "#e06c75"
    #: Drawn behind cover art while it loads, and for games with no art.
    placeholder: str = "#1a1a22"

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> "Theme":
        """Build a theme from a dict, ignoring unknown keys.

        Unknown keys are dropped rather than raising, so a theme file written
        by a newer version still loads in an older one.
        """
        fields = {f for f in cls.__dataclass_fields__}
        return cls(**{k: v for k, v in data.items() if k in fields})

    @classmethod
    def load(cls, path: Path) -> "Theme":
        return cls.from_dict(json.loads(Path(path).read_text(encoding="utf-8")))

    def save(self, path: Path) -> None:
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(json.dumps(self.to_dict(), indent=2), encoding="utf-8")


