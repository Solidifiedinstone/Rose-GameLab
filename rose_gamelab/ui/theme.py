DEFAULT_THEME = "rose-dark"


def get_theme(name: str) -> Theme:
    """Look up a built-in theme, falling back to the default."""
    return THEMES.get(name, THEMES[DEFAULT_THEME])


def list_theme_names() -> list[tuple[str, str]]:
    """(id, display name) for every built-in theme."""
    return [(key, theme.name) for key, theme in THEMES.items()]


